def test_live_runner_processes_launch_with_real_codex_events(tmp_path: Path) -> None:
    requests: list[tuple[str, str, dict]] = []
    workspace_path = tmp_path / "workspace"
    artifact_path = tmp_path / "artifacts"
    log_path = tmp_path / "logs"
    cache_path = tmp_path / "cache"
    workspace_path.mkdir()
    artifact_path.mkdir()
    log_path.mkdir()
    cache_path.mkdir()
    subprocess.run(["git", "-C", str(workspace_path), "init"], check=True, capture_output=True, text=True)

    fake_codex = _write_fake_codex_script(tmp_path)
    launch_payload = {
        "lane_id": "lane-88",
        "agent_session_id": "session-88",
        "lane_metadata": {"environment_identity": "docker://lane-88", "branch_name": "orcha/issue-88-attempt-1"},
        "issue_context": {"issue_number": 88, "title": "Wire live Codex runner"},
        "instruction_bundle": {
            "system_prompt": "Stay within repo policy.",
            "task": "Add the requested lane note.",
            "issue_body": "Create one note file as proof of execution.",
        },
        "policy": {"approval_posture": "high-trust"},
        "artifact_destinations": {
            "workspace_uri": workspace_path.as_uri(),
            "artifact_uri": artifact_path.as_uri(),
            "log_uri": log_path.as_uri(),
            "cache_uri": cache_path.as_uri(),
        },
        "secret_references": [],
        "tool_permissions": ["git.read", "shell.exec"],
        "required_capabilities": ["stream-events"],
    }
    launches = [launch_payload]

    def handler(request: httpx.Request) -> httpx.Response:
        if request.method == "GET" and request.url.path == "/v1/runner/launches/next":
            if launches:
                return httpx.Response(status_code=200, json=launches.pop(0))
            return httpx.Response(status_code=204)
        if request.method == "POST":
            payload = json.loads(request.content.decode("utf-8"))
            requests.append((request.method, request.url.path, payload))
            return httpx.Response(status_code=200, json={"ok": True})
        return httpx.Response(status_code=404, json={"detail": "not found"})

    transport = httpx.MockTransport(handler)
    with httpx.Client(transport=transport, base_url="http://worker.test") as client:
        processed = process_pending_runner_launches(client, max_launches=2, config=_live_runner_config(codex_bin=str(fake_codex)))

    assert processed == 1
    assert requests[0][1] == "/v1/runner/lanes/lane-88/handshake"
    assert requests[0][2]["environment_identity"] == "docker://lane-88"
    event_types = [payload["event_type"] for method, path, payload in requests if path.endswith("/events")]
    assert event_types[:3] == ["status_summary", "status_summary", "turn_started"]
    assert "tool_call_started" in event_types
    assert "tool_call_finished" in event_types
    assert "artifact_created" in event_types
    assert "token_usage_reported" in event_types
    assert "turn_completed" in event_types
    assert event_types[-1] == "session_completed"

    result_payload = json.loads((artifact_path / "codex-run-result.json").read_text(encoding="utf-8"))
    assert result_payload["success"] is True
    assert result_payload["changed_files"] == ["lane-note.md"]
    assert (workspace_path / "lane-note.md").read_text(encoding="utf-8") == "generated by fake codex\n"
    assert (artifact_path / "codex-last-message.md").read_text(encoding="utf-8").strip() == "Fake Codex lane complete."


