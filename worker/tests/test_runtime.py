def test_api_probe_job_succeeds() -> None:
    port = _find_free_port()
    server = _ThreadedTCPServer(("127.0.0.1", port), _OkHandler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        job = WorkerJob(
            job_id=uuid4(),
            job_type="platform.api_probe",
            idempotency_key="probe-1",
            requested_by=RequestedBy(type="system", id="test"),
            payload={"url": f"http://127.0.0.1:{port}/health"},
        )
        result = run_job(job)
        assert result.status == "succeeded"
        assert result.output is not None
        assert result.output["status_code"] == 200
        assert "ok" in result.output["body_preview"]
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=2)


