def test_lifespan_shutdown_cancels_active_lanes_and_releases_environments(monkeypatch) -> None:
    with tempfile.TemporaryDirectory() as temp_dir:
        temp_path = Path(temp_dir)
        remote_root = temp_path / "remote-execution"
        _configure_env(
            f"sqlite+pysqlite:///{temp_path / 'runtime.db'}",
            remote_execution_root=remote_root,
            orchestration_enabled=False,
        )
        clone_url = _build_remote_repo(temp_path)
        cleanup_requests: list[RuntimeCleanupRequest] = []

        class _FakeRuntimeProvider:
            name = "docker"

            def provision(self, request) -> RuntimeProvisionResult:
                lane_root = remote_root / "lanes" / request.environment_id
                workspace_path = (lane_root / "workspace").resolve()
                artifact_path = (lane_root / "artifacts").resolve()
                log_path = (lane_root / "logs").resolve()
                cache_path = (lane_root / "cache").resolve()
                for path in (artifact_path, log_path, cache_path):
                    path.mkdir(parents=True, exist_ok=True)
                if workspace_path.exists():
                    shutil.rmtree(workspace_path)
                workspace_path.mkdir(parents=True, exist_ok=True)
                return RuntimeProvisionResult(
                    runtime_provider=self.name,
                    container_handle=f"docker://{request.environment_id}",
                    workspace_uri=workspace_path.as_uri(),
                    artifact_uri=artifact_path.as_uri(),
                    log_uri=log_path.as_uri(),
                    cache_uri=cache_path.as_uri(),
                    workspace_path=workspace_path,
                    artifact_path=artifact_path,
                    log_path=log_path,
                    cache_path=cache_path,
                    status="Ready",
                    provider_metadata={"container_removed": False},
                )

            def can_reuse(self, environment) -> bool:
                return True

            def cleanup(self, request: RuntimeCleanupRequest) -> RuntimeCleanupResult:
                cleanup_requests.append(request)
                workspace_path = Path(request.workspace_uri.removeprefix("file://")) if request.workspace_uri else None
                if workspace_path is not None and workspace_path.exists():
                    shutil.rmtree(workspace_path)
                return RuntimeCleanupResult(
                    status="Terminated",
                    terminated_at=datetime.now(timezone.utc),
                    provider_metadata={
                        "container_removed": True,
                        "container_reference": request.container_handle.removeprefix("docker://") if request.container_handle else None,
                    },
                )

        fake_provider = _FakeRuntimeProvider()
        monkeypatch.setattr(execution_runtime_module, "build_runtime_provider", lambda settings=None: fake_provider)

        with TestClient(app):
            session = get_session_factory()()
            try:
                _seed_ready_work_item(session, clone_url=clone_url, issue_number=56)
            finally:
                session.close()

            session = get_session_factory()()
            try:
                summary = OrchestrationRuntimeService(session).run_cycle(max_claims=1)
                session.commit()
                assert summary.claimed == 1
                assert summary.provisioned == 1
            finally:
                session.close()

            lane = _load_lane()
            assert lane is not None
            assert lane.state == "Provisioning"
            assert lane.execution_environment is not None
            assert lane.execution_environment.status == "Ready"
            workspace_path = Path(lane.execution_environment.workspace_uri.removeprefix("file://"))
            assert workspace_path.exists()

        lane = _load_lane()
        assert lane is not None
        assert lane.state == "Cancelled"
        assert lane.finished_at is not None
        assert lane.execution_environment is not None
        assert lane.execution_environment.status == "Terminated"
        assert lane.execution_environment.terminated_at is not None
        assert lane.agent_session is not None
        assert lane.agent_session.status == "failed"
        assert lane.agent_session.last_error_category == "integration"
        assert len(cleanup_requests) == 1
        assert cleanup_requests[0].disposition == "terminate"
        assert cleanup_requests[0].reason == "runtime.api_shutdown"
        assert not workspace_path.exists()
        _reset_env()


