def _configure_env(
    database_url: str,
    *,
    remote_execution_root: Path,
    orchestration_enabled: bool,
    tick_interval_seconds: str = "5",
    live_runner_codex_bin: Path | None = None,
) -> None:
    os.environ["AGENT_CORE_AUTH_DISABLED"] = "1"
    os.environ["AGENT_CORE_DATABASE_URL"] = database_url
    os.environ["AGENT_CORE_CRYPTO_SEED"] = "agent-core-test-seed"
    os.environ["AGENT_CORE_INITIAL_ORG_NAME"] = "Primary"
    os.environ["AGENT_CORE_INITIAL_ORG_SLUG"] = "primary"
    os.environ["AGENT_CORE_REMOTE_EXECUTION_ROOT"] = str(remote_execution_root)
    os.environ["AGENT_CORE_RUNTIME_PROVIDER_NAMESPACE"] = "test-namespace"
    os.environ["AGENT_CORE_ORCHESTRATION_LOOP_ENABLED"] = "1" if orchestration_enabled else "0"
    os.environ["AGENT_CORE_ORCHESTRATION_TICK_INTERVAL_SECONDS"] = tick_interval_seconds
    os.environ["AGENT_CORE_ORCHESTRATION_MAX_CLAIMS_PER_TICK"] = "2"
    if live_runner_codex_bin is not None:
        os.environ["AGENT_CORE_LIVE_RUNNER_CODEX_BIN"] = str(live_runner_codex_bin)
    else:
        os.environ.pop("AGENT_CORE_LIVE_RUNNER_CODEX_BIN", None)
    os.environ["AGENT_CORE_LIVE_RUNNER_CODEX_SANDBOX"] = "workspace-write"
    get_settings.cache_clear()
    reset_database_state()


def _reset_env() -> None:
    for key in (
        "AGENT_CORE_DATABASE_URL",
        "AGENT_CORE_REMOTE_EXECUTION_ROOT",
        "AGENT_CORE_RUNTIME_PROVIDER_NAMESPACE",
        "AGENT_CORE_ORCHESTRATION_LOOP_ENABLED",
        "AGENT_CORE_ORCHESTRATION_TICK_INTERVAL_SECONDS",
        "AGENT_CORE_ORCHESTRATION_MAX_CLAIMS_PER_TICK",
        "AGENT_CORE_LIVE_RUNNER_CODEX_BIN",
        "AGENT_CORE_LIVE_RUNNER_CODEX_SANDBOX",
    ):
        os.environ.pop(key, None)
    get_settings.cache_clear()
    reset_database_state()


def _git(path: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(path), *args],
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout.strip()


def _run(*args: str) -> str:
    result = subprocess.run(list(args), check=True, capture_output=True, text=True)
    return result.stdout.strip()


def _build_remote_repo(root: Path) -> str:
    bare_repo = root / "remote.git"
    source_repo = root / "source"
    _run("git", "init", "--bare", str(bare_repo))
    _run("git", "init", "--initial-branch=dev", str(source_repo))
    _git(source_repo, "config", "user.email", "test@example.com")
    _git(source_repo, "config", "user.name", "Test User")
    (source_repo / "README.md").write_text("# Fixture\n", encoding="utf-8")
    _git(source_repo, "add", "README.md")
    _git(source_repo, "commit", "-m", "Initial commit")
    _git(source_repo, "remote", "add", "origin", bare_repo.as_uri())
    _git(source_repo, "push", "-u", "origin", "dev")
    return bare_repo.as_uri()


